    /// Persian is the last stored language choice; English until the
    /// one-time picker runs (same flow as Android's language picker).
    static var language: String {
        get { UserDefaults.standard.string(forKey: "app_language") ?? "en" }
        set { UserDefaults.standard.set(newValue, forKey: "app_language") }
    }

    static var usesPersian: Bool { language == "fa" }

    static func t(_ key: String) -> String {
        guard usesPersian else { return key }
        return fa[key] ?? faExtras[key] ?? key
    }

    /// Ordered %-substitution, the Android tf() contract.
    static func tf(_ key: String, _ args: String...) -> String {
        var s = t(key)
        for arg in args {
            if let r = s.range(of: "%s") {
                s.replaceSubrange(r, with: arg)
            } else if let r = s.range(of: "%d") {
                s.replaceSubrange(r, with: arg)
            }
        }
        return s
    }
